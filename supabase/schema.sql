-- ---------- Administradores ----------
create table if not exists public.admin_users (
  user_id uuid primary key references auth.users (id) on delete cascade,
  created_at timestamptz not null default now()
);
alter table public.admin_users enable row level security;
revoke all on table public.admin_users from anon, authenticated;

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (select 1 from public.admin_users where user_id = auth.uid());
$$;

-- ---------- Solicitações de orçamento (formulário do site) ----------
create table if not exists public.solicitacoes (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  nome text not null,
  telefone text not null,
  email text not null,
  servico text not null,
  mensagem text,
  status text not null default 'pendente' check (status in ('pendente', 'atendido')),
  observacoes text not null default ''
);
create index if not exists solicitacoes_created_at_idx on public.solicitacoes (created_at desc);
alter table public.solicitacoes enable row level security;
revoke all on table public.solicitacoes from anon, authenticated;
grant insert on table public.solicitacoes to anon;
grant select, update, delete on table public.solicitacoes to authenticated;

drop policy if exists "Publico pode enviar solicitacoes" on public.solicitacoes;
create policy "Publico pode enviar solicitacoes" on public.solicitacoes
  for insert to anon with check (status = 'pendente' and observacoes = '');
drop policy if exists "Administradores podem visualizar solicitacoes" on public.solicitacoes;
create policy "Administradores podem visualizar solicitacoes" on public.solicitacoes
  for select to authenticated using (public.is_admin());
drop policy if exists "Administradores podem atualizar solicitacoes" on public.solicitacoes;
create policy "Administradores podem atualizar solicitacoes" on public.solicitacoes
  for update to authenticated using (public.is_admin()) with check (status in ('pendente', 'atendido'));
drop policy if exists "Administradores podem excluir solicitacoes" on public.solicitacoes;
create policy "Administradores podem excluir solicitacoes" on public.solicitacoes
  for delete to authenticated using (public.is_admin());

-- ---------- Textos e fotos do site ----------
create table if not exists public.site_content (
  id text primary key default 'principal' check (id = 'principal'),
  content jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);
alter table public.site_content enable row level security;
revoke all on table public.site_content from anon, authenticated;
grant select on table public.site_content to anon, authenticated;
grant insert, update, delete on table public.site_content to authenticated;

drop policy if exists "Publico pode ler conteudo do site" on public.site_content;
create policy "Publico pode ler conteudo do site" on public.site_content
  for select to anon, authenticated using (true);
drop policy if exists "Administrador gerencia conteudo do site" on public.site_content;
create policy "Administrador gerencia conteudo do site" on public.site_content
  for all to authenticated using (public.is_admin()) with check (public.is_admin());

-- ---------- Portfólio ----------
create table if not exists public.portfolio_projects (
  id bigint generated by default as identity primary key,
  title text not null,
  system text not null default '',
  location text not null default '',
  clients text not null default '',
  description text not null default '',
  images text[] not null default '{}',
  sort_order integer not null default 0,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists portfolio_projects_sort_idx on public.portfolio_projects (sort_order);

-- ---------- Clientes (faixa animada) ----------
create table if not exists public.clients (
  id bigint generated by default as identity primary key,
  name text not null,
  logo_url text not null default '',
  sort_order integer not null default 0,
  active boolean not null default true,
  created_at timestamptz not null default now()
);
create index if not exists clients_sort_idx on public.clients (sort_order);

alter table public.portfolio_projects enable row level security;
alter table public.clients enable row level security;
revoke all on table public.portfolio_projects, public.clients from anon, authenticated;
grant select on table public.portfolio_projects, public.clients to anon, authenticated;
grant insert, update, delete on table public.portfolio_projects, public.clients to authenticated;

drop policy if exists "Publico le obras publicadas" on public.portfolio_projects;
create policy "Publico le obras publicadas" on public.portfolio_projects
  for select to anon, authenticated using (active or public.is_admin());
drop policy if exists "Administrador gerencia obras do portfolio" on public.portfolio_projects;
create policy "Administrador gerencia obras do portfolio" on public.portfolio_projects
  for all to authenticated using (public.is_admin()) with check (public.is_admin());

drop policy if exists "Publico le clientes ativos" on public.clients;
create policy "Publico le clientes ativos" on public.clients
  for select to anon, authenticated using (active or public.is_admin());
drop policy if exists "Administrador gerencia clientes" on public.clients;
create policy "Administrador gerencia clientes" on public.clients
  for all to authenticated using (public.is_admin()) with check (public.is_admin());

